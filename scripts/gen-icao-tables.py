#!/usr/bin/env python3
"""Write skycued's ICAO tables from the page's copy (one source for both).

usage: python3 -I gen-icao-tables.py APP_PURE_JS OUT_INC
       python3 -I gen-icao-tables.py --check APP_PURE_JS INC

Reads three array literals out of www/app_pure.js:

  var ICAO_BLOCKS = [ [0xFIRST, 0xLAST, 'Name'], ... ];   address allocation
  var MILITARY_BLOCKS = [ [0xFIRST, 0xLAST], ... ];        military blocks
  var MILITARY_CALLSIGN_PREFIXES = ['RCH', ...];           callsign prefixes

(hex numbers, '...' or "..." strings, // and /* */ comments; the scan
stops at each table's closing ], so the rest of the file is not read) and writes them as the C++
arrays kIcaoBlocks, kMilitaryBlocks and kMilitaryCallsignPrefixes that
skycued/src/icao_class.cpp includes. Each block table must be sorted
by first address with first <= last <= 0xFFFFFF and no overlaps.

Exit status: 0 written (or, with --check, INC is what would be written);
1 with --check when INC differs or is missing; 2 when a table is missing,
a row does not parse, or a block table is unsorted or overlapping.
Standard library only; Python 3.6 or later.
"""

import re
import sys

HEADER = ("// generated by scripts/gen-icao-tables.py from www/app_pure.js; do not edit\n"
          "// (rerun: python3 -I scripts/gen-icao-tables.py www/app_pure.js "
          "skycued/src/icao_tables.inc)\n")


class TableError(Exception):
    pass


class Literal:
    """An array literal's text between its [ and matching ], with comments
    blanked to spaces (newlines kept, so offsets still give line numbers)."""

    def __init__(self, name, text, first_line):
        self.name = name
        self.text = text
        self.first_line = first_line

    def line(self, pos):
        return self.first_line + self.text.count("\n", 0, pos)

    def error(self, pos, what):
        return TableError("%s (line %d): %s" % (self.name, self.line(pos), what))


def literal_body(src, name):
    """The literal `var NAME = [ ... ];`. The scan knows '...' and "..."
    strings and // and /* */ comments, and stops at the matching ], so what
    follows the table is never read."""
    m = re.search(r"\bvar\s+" + re.escape(name) + r"\s*=\s*\[", src)
    if not m:
        raise TableError("table %s not found" % name)
    start = m.end()
    first_line = src.count("\n", 0, start) + 1

    def line(pos):
        return src.count("\n", 0, pos) + 1

    out = []
    depth = 1
    i, n = start, len(src)
    while i < n:
        ch = src[i]
        if ch in "'\"":
            j = i + 1
            while j < n and src[j] != ch and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            if j >= n or src[j] != ch:
                raise TableError("%s (line %d): unterminated string" % (name, line(i)))
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            if j < 0:
                raise TableError("%s (line %d): unterminated /* comment" % (name, line(i)))
            out.append(re.sub(r"[^\n]", " ", src[i:j + 2]))
            i = j + 2
        else:
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    if not re.match(r"\s*;", src[i + 1:i + 64]):
                        raise TableError("%s (line %d): no ; after its closing ]" % (name, line(i)))
                    return Literal(name, "".join(out), first_line)
            out.append(ch)
            i += 1
    raise TableError("%s (line %d): no closing ]" % (name, first_line))


STRING = r"""(?:'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)")"""
HEX = r"0[xX]([0-9A-Fa-f]+)"


def unescape(s):
    def rep(m):
        c = m.group(1)
        if c in "'\\\"":
            return c
        raise TableError("unsupported escape \\%s" % c)
    return re.sub(r"\\(.)", rep, s)


def string_value(m, group):
    """The text of a STRING match whose quote groups start at `group`."""
    v = m.group(group)
    return unescape(v if v is not None else m.group(group + 1))


def parse_rows(lit, with_name):
    """[first, last(, 'name')] rows of a block table."""
    body, name = lit.text, lit.name
    row_re = re.compile(r"\[\s*" + HEX + r"\s*,\s*" + HEX +
                        (r"\s*,\s*" + STRING if with_name else "") + r"\s*\]")
    rows = []
    starts = []
    pos = 0
    sep = re.compile(r"\s*")
    after = re.compile(r"\s*(,|$)")
    while True:
        pos = sep.match(body, pos).end()
        if pos >= len(body):
            break
        m = row_re.match(body, pos)
        if not m:
            snippet = body[pos:pos + 40].split("\n")[0].strip()
            raise lit.error(pos, "row %d does not parse: %s" % (len(rows) + 1, snippet))
        first, last = int(m.group(1), 16), int(m.group(2), 16)
        rows.append((first, last, string_value(m, 3)) if with_name else (first, last))
        starts.append(pos)
        pos = m.end()
        nxt = after.match(body, pos)
        if not nxt:
            raise lit.error(pos, "no comma after row %d" % len(rows))
        pos = nxt.end()
    if not rows:
        raise lit.error(0, "table is empty")
    for i, r in enumerate(rows):
        if not (0 <= r[0] <= r[1] <= 0xFFFFFF):
            raise lit.error(starts[i], "row %d: need first <= last <= 0xFFFFFF" % (i + 1))
        if i > 0 and rows[i - 1][1] >= r[0]:
            raise lit.error(starts[i], "row %d is not after row %d (unsorted or overlapping)" % (i + 1, i))
    return rows


def parse_strings(lit):
    body = lit.text
    items = []
    pos = 0
    item_re = re.compile(r"\s*" + STRING + r"\s*(,|$)")
    while pos < len(body) and body[pos:].strip():
        m = item_re.match(body, pos)
        if not m:
            snippet = body[pos:pos + 40].strip().split("\n")[0]
            raise lit.error(pos, "item %d does not parse: %s" % (len(items) + 1, snippet))
        s = string_value(m, 1)
        if not s:
            raise lit.error(pos, "item %d is empty" % (len(items) + 1))
        items.append(s)
        pos = m.end()
    if not items:
        raise lit.error(0, "table is empty")
    return items


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(src):
    icao = parse_rows(literal_body(src, "ICAO_BLOCKS"), True)
    mil = parse_rows(literal_body(src, "MILITARY_BLOCKS"), False)
    prefixes = parse_strings(literal_body(src, "MILITARY_CALLSIGN_PREFIXES"))
    out = [HEADER, "\n", "static const IcaoBlock kIcaoBlocks[] = {\n"]
    for first, last, name in icao:
        out.append("    {0x%06X, 0x%06X, %s},\n" % (first, last, c_string(name)))
    out.append("};\n\nstatic const MilitaryBlock kMilitaryBlocks[] = {\n")
    for first, last in mil:
        out.append("    {0x%06X, 0x%06X},\n" % (first, last))
    out.append("};\n\nstatic const char* const kMilitaryCallsignPrefixes[] = {\n")
    for p in prefixes:
        out.append("    %s,\n" % c_string(p))
    out.append("};\n")
    return "".join(out)


def read_text(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def main(argv):
    check = False
    args = list(argv)
    if args and args[0] == "--check":
        check = True
        args = args[1:]
    if len(args) != 2 or any(a.startswith("-") for a in args):
        sys.stderr.write(__doc__.split("\n\n")[1] + "\n")
        return 2
    app_js, inc = args
    try:
        text = render(read_text(app_js))
    except (TableError, OSError, UnicodeDecodeError) as e:
        sys.stderr.write("gen-icao-tables: %s: %s\n" % (app_js, e))
        return 2
    if check:
        try:
            current = read_text(inc)
        except (OSError, UnicodeDecodeError):
            current = None
        if current != text:
            sys.stderr.write("gen-icao-tables: %s is stale; rerun: python3 -I scripts/gen-icao-tables.py "
                             "www/app_pure.js skycued/src/icao_tables.inc\n" % inc)
            return 1
        return 0
    try:
        with open(inc, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    except OSError as e:
        sys.stderr.write("gen-icao-tables: %s: %s\n" % (inc, e))
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
